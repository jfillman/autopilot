func fixtureDefinition(reg *tools.Registry) (*definitions.Definition, []string) {
	var names []string
	for _, n := range reg.Names() {
		names = append(names, n)
	}
	d := &definitions.Definition{Name: "fixture-agent", Kind: "task", ReposAllow: []string{"*/*"}, DenyPaths: reg.BaselineDenyPaths,
		RawProfile: json.RawMessage(`{"glidepath":{"apps":["*"]}}`)}
	return d, names
}

func fixtureSession(c map[string]any, toolNames []string) *session.Session {
	s := &session.Session{ID: c["id"].(string), Principal: c["principal"].(string), Agent: c["agent"].(string)}
	s.TaskID, _ = c["task"].(string)
	if r, ok := c["run"].(string); ok && r != "" {
		s.Run = &r
	}
	s.Limits = clearclient.Limits{TierCeiling: "T2", Tools: toolNames}
	return s
}

type env struct {
	h     map[string]dispatch.Handler
	w     *world
	gp    *Glidepath
	git   *GitHub
	sess  *session.Session
	clock *float64
}

func newEnv(t *testing.T, tok map[string]string, c *writesCase, session map[string]any) *env {
	t.Helper()
	w := newWorld(t, c.Routes, c.Default)
	dir := t.TempDir()
	write := func(name, v string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(v+"\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		return p
	}
	reg := tools.Default()
	def, names := fixtureDefinition(reg)
	cfg := HangarConfig{Definition: func(string) *definitions.Definition { return def }, Tools: reg}
	e := &env{w: w, sess: fixtureSession(session, names)}
	if c.Glidepath {
		gp, err := NewGlidepath(w.srv.URL+"/gp", write("gp", tok["glidepath"]), c.OBO, 5*time.Second, true)
		if err != nil {
			t.Fatal(err)
		}
		asClient(w, gp.hc)
		asClient(w, gp.streamHC)
		gp.retry.retries = 0
		if c.Clock {
			now := new(float64)
			e.clock = now
			gp.clock = func() float64 { return *now }
			gp.sleep = func(_ context.Context, d time.Duration) bool { *now += d.Seconds(); return true }
		}
		cfg.Glidepath, e.gp = gp, gp
	}
	if c.Git {
		g, err := NewGitHub(GitHubOptions{API: w.srv.URL, BrokerURL: w.srv.URL + "/b", TokenFile: write("agent", tok["agent"]), Owners: []string{"o"}, AllowHTTP: true, Timeout: 5 * time.Second})
		if err != nil {
			t.Fatal(err)
		}
		asClient(w, g.apiHC)
		asClient(w, g.brokerHC)
		g.retry.retries = 0
		cfg.GitHub, e.git = g, g
	}
	if len(c.Namespaces) > 0 {
		kube := &KubeReader{Server: w.srv.URL + "/k", TokenFile: write("kube", tok["kube"]), Timeout: 5 * time.Second}
		kube.hc = client(nil, time.Second, 4)
		asClient(w, kube.hc)
		as, err := NewArgoSync(kube, c.Namespaces)
		if err != nil {
			t.Fatal(err)
		}
		cfg.ArgoSync = as
	}
	e.h = hangarHandlers(cfg)
	return e
}

func (e *env) requests() []wsReq {
	e.w.mu.Lock()
	defer e.w.mu.Unlock()
	return append([]wsReq(nil), e.w.seen...)
}

// dropEmpty removes nulls and empty lists and objects: Python's receipt writes `paths: []` where Go's omits it.
func dropEmpty(v any) any {
	m, ok := v.(map[string]any)
	if !ok {
		return v
	}
	for k, e := range m {
		if l, isList := e.([]any); e == nil || (isList && len(l) == 0) {
			delete(m, k)
		}
	}
	if len(m) == 0 {
		return nil
	}
	return m
}

func scrubAt(v any) any {
	switch x := v.(type) {
	case map[string]any:
		for k, e := range x {
			if k == "at" {
				x[k] = "T"
			} else {
				x[k] = scrubAt(e)
			}
		}
	case []any:
		for i, e := range x {
			x[i] = scrubAt(e)
		}
	}
	return v
}

func TestWriteToolsEqualPython(t *testing.T) {
	var f writesFile
	loadJSON(t, "writes.json", &f)
	if len(f.Cases) < 250 {
		t.Fatalf("only %d cases: the fixture is not the one the generator writes", len(f.Cases))
	}
	n := map[string]int{}
	for _, c := range f.Cases {
		n[strings.SplitN(c.Tool, ".", 2)[0]]++
		switch {
		case c.Go != nil:
			n["differs"]++
		case c.Denied != nil:
			n["denied"]++
		case c.Error != nil:
			n["error"]++
		default:
			n["result"]++
		}
		t.Run(c.Name, func(t *testing.T) {
			e := newEnv(t, f.Tokens, &c, c.Session)
			args := expand(c.Args).(map[string]any)
			var got any
			var err error
			ctx, cancel := context.WithTimeout(context.Background(), 300*time.Second)
			defer cancel()
			switch {
			case strings.HasPrefix(c.Tool, "direct:"):
				got, err = runDirect(ctx, e, strings.TrimPrefix(c.Tool, "direct:"), args)
			default:
				h := e.h[c.Tool]
				if h == nil {
					t.Fatalf("no handler for %s", c.Tool)
				}
				got, err = h(ctx, e.sess, args)
			}
			wantReqs, wantResult, wantDenied, wantErr := c.Requests, c.Result, c.Denied, c.Error
			_ = wantResult
			if c.Go != nil {
				if c.Why == "" {
					t.Fatal("a case Go answers differently says why")
				}
				wantResult, wantDenied, wantErr = c.Go.Result, c.Go.Denied, c.Go.Error
				if c.Go.Requests != nil {
					wantReqs = *c.Go.Requests
				}
			}
			gotReqs := dropGoOnlyReads(e.requests(), wantReqs)
			if len(wantReqs) == 0 {
				wantReqs = nil
			}
			if len(gotReqs) == 0 {
				gotReqs = nil
			}
			if !reflect.DeepEqual(normalize(t, expand(normalize(t, wantReqs))), normalize(t, gotReqs)) {
				t.Fatalf("requests (the call answered %s / %v)\n want %s\n  got %s", short(got), err, short(expand(normalize(t, wantReqs))), short(gotReqs))
			}
			switch {
			case wantDenied != nil:
				var den *core.Denied
				if !errors.As(err, &den) {
					t.Fatalf("want a refusal %+v, got %v / %v", wantDenied, short(got), err)
				}
				if any(den.Rule) != wantDenied.Rule || any(den.Message) != wantDenied.Message || any(den.Hint) != wantDenied.Hint {
					t.Fatalf("refusal\n want %+v\n  got %+v", wantDenied, den)
				}
			case wantErr != nil:
				if err == nil {
					t.Fatalf("want error %+v, got %v", wantErr, short(got))
				}
				if r := dispatch.ErrorResult(err); r != wantErr.OutcomeResult {
					t.Fatalf("outcome result:\n want %q\n  got %q", wantErr.OutcomeResult, r)
				}
				if m := dispatch.BackendError(err); m != wantErr.AgentError {
					t.Fatalf("agent error:\n want %q\n  got %q", wantErr.AgentError, m)
				}
			default:
				if err != nil {
					t.Fatalf("want a result, got %v", err)
				}
				want := scrubAt(normalize(t, expand(wantResult)))
				have := scrubAt(normalize(t, got))
				if !reflect.DeepEqual(want, have) {
					t.Fatalf("result\n want %s\n  got %s", short(want), short(have))
				}
				if spec, ok := tools.Default().Get(c.Tool); ok && c.Go == nil {
					// the receipt the outcome carries is Python's for the same result
					wantEffect, gotEffect := dropEmpty(normalize(t, c.Effect)), dropEmpty(normalize(t, dispatch.Effect(spec, args, got)))
					if !reflect.DeepEqual(wantEffect, gotEffect) {
						t.Fatalf("effect\n want %s\n  got %s", short(wantEffect), short(gotEffect))
					}
				}
			}
			for _, r := range gotReqs {
				for _, v := range r.Headers {
					if strings.Contains(v, "ghs_") && !strings.HasPrefix(v, "Bearer ghs_fixturetoken") {
						t.Fatalf("a token went somewhere odd: %v", r.Headers)
					}
				}
			}
		})
	}
	if n["glidepath"] < 100 || n["repo"] < 80 || n["argo"] < 15 || n["direct:ensure_pr"]+n["direct:find_pr"] < 10 || n["denied"] < 60 || n["error"] < 30 || n["result"] < 100 || n["differs"] < 8 {
		t.Fatalf("the fixture's cases: %v", n)
	}
}

func runDirect(ctx context.Context, e *env, method string, a map[string]any) (any, error) {
	files := []File{}
	for _, x := range anyList(a["files"]) {
		m := obj(x)
		files = append(files, File{Path: m["path"].(string), Content: m["content"].(string)})
	}
	meta := map[string]string{}
	for k, v := range obj(a["meta"]) {
		meta[k] = v.(string)
	}
	body, _ := a["body"].(string)
	in := OpenPRInput{Repo: a["repo"].(string), Branch: a["branch"].(string), Title: str(a, "title"), Base: "main", Files: files, Meta: meta, Body: body}
	switch method {
	case "ensure_pr":
		return e.git.EnsurePR(ctx, in)
	case "find_pr":
		m, err := e.git.FindPR(ctx, in.Repo, in.Branch)
		if m == nil && err == nil {
			return nil, nil
		}
		return m, err
	}
	return nil, errors.New("no such method " + method)
}

var goOnlyRead = regexp.MustCompile(`^GET /repos/[^/]+/[^/?]+$|^GET /repos/[^/]+/[^/]+/contents/[^?]*\?ref=[0-9a-f]{40}$|^GET /repos/[^/]+/[^/]+/git/commits/[0-9a-f]{40}$`)

// dropGoOnlyReads takes out of what Go sent the reads Python never makes and the fixtures do not carry: the repository (its
// default branch), the base commit's contents (a file may not take a directory's place) and a head commit's trailer. They
// are GETs of the closed list; each has its own test (review_fixes_test.go). A read the case expects is kept.
func dropGoOnlyReads(got, want []wsReq) []wsReq {
	left := map[string]int{}
	for _, w := range want {
		left[w.Method+" "+w.Target]++
	}
	var out []wsReq
	for _, g := range got {
		k := g.Method + " " + g.Target
		if left[k] > 0 {
			left[k]--
			out = append(out, g)
			continue
		}
		if goOnlyRead.MatchString(k) {
			continue
		}
		out = append(out, g)
	}
	return out
}
