// The equivalence tests of the S5b tools: testdata/writes.json is generated by driving the Python handlers
// (tools/gen_gateway_writes.py: gateway.hangar_handlers over glidepath_api.GlidepathAPI, github_pr.GitHubPRs,
// argo_sync.ArgoSync and cicd_propose) over canned upstream answers. Each case here serves the same answers and requires the
// same requests (method, target, the headers that matter, the JSON body) and the same result, refusal, or error text and
// class. A case with "go" is a place Go deliberately differs: the expectation is Go's, and "why" says why.
//
// One server stands for every upstream by path prefix (/gp glidepath-api, /b the token broker, / GitHub, /k Kubernetes). A
// transport that wraps the client's records every request, so a request that fails to send is still seen, and makes the
// failures Python's fake raised (refused, a timeout, a reset) the errors a network gives.

type writesFile struct {
	Tokens map[string]string `json:"tokens"`
	Cases  []writesCase      `json:"cases"`
}

type writesCase struct {
	Name       string                     `json:"name"`
	Tool       string                     `json:"tool"`
	Args       map[string]any             `json:"args"`
	Session    map[string]any             `json:"session"`
	Routes     map[string]any             `json:"routes"`
	Default    map[string]any             `json:"default"`
	OBO        bool                       `json:"obo"`
	Git        bool                       `json:"git"`
	Glidepath  bool                       `json:"glidepath"`
	Clock      bool                       `json:"clock"`
	Namespaces []string                   `json:"namespaces"`
	Requests   []wsReq                    `json:"requests"`
	Result     any                        `json:"result"`
	Effect     any                        `json:"effect"`
	Denied     *wsDenied                  `json:"denied"`
	Error      *errorJSON                 `json:"error"`
	Go         *writesGo                  `json:"go"`
	Why        string                     `json:"why"`
	Extra      map[string]json.RawMessage `json:"-"`
}

type writesGo struct {
	Result   any        `json:"result"`
	Denied   *wsDenied  `json:"denied"`
	Error    *errorJSON `json:"error"`
	Requests *[]wsReq   `json:"requests"`
}

type wsDenied struct{ Rule, Message, Hint any }

type wsReq struct {
	Method  string            `json:"method"`
	Target  string            `json:"target"`
	Headers map[string]string `json:"headers"`
	Body    any               `json:"body"`
}

var keepHeaders = []string{"authorization", "x-glidepath-authorization", "accept", "idempotency-key", "x-glidepath-dry-run", "x-glidepath-on-behalf-of", "x-github-api-version"}

// world is the server and the recorder of one case.
type world struct {
	t      *testing.T
	mu     sync.Mutex
	routes map[string]any
	def    map[string]any
	count  map[string]int
	picked map[string]map[string]any
	next   int
	seen   []wsReq
	srv    *httptest.Server
	realTr http.RoundTripper
}

func newWorld(t *testing.T, routes map[string]any, def map[string]any) *world {
	routes = expand(routes).(map[string]any)
	w := &world{t: t, routes: routes, def: def, count: map[string]int{}, picked: map[string]map[string]any{}}
	w.srv = httptest.NewServer(http.HandlerFunc(w.serve))
	w.realTr = http.DefaultTransport.(*http.Transport).Clone()
	t.Cleanup(w.srv.Close)
	return w
}

func (w *world) pick(key string) map[string]any {
	w.mu.Lock()
	defer w.mu.Unlock()
	r, ok := w.routes[key]
	if !ok {
		return w.def
	}
	if l, isList := r.([]any); isList {
		i := w.count[key]
		w.count[key] = i + 1
		if i >= len(l) {
			i = len(l) - 1
		}
		return l[i].(map[string]any)
	}
	return r.(map[string]any)
}

func (w *world) serve(rw http.ResponseWriter, r *http.Request) {
	route := w.routesFor(r)
	if lines, ok := route["lines"].([]any); ok {
		rw.Header().Set("Content-Type", "text/event-stream")
		rw.WriteHeader(statusOf2(route))
		for _, l := range lines {
			_, _ = rw.Write([]byte(l.(string)))
		}
		rw.(http.Flusher).Flush()
		if route["then"] == "reset" {
			c, _, _ := rw.(http.Hijacker).Hijack()
			if tc, ok := c.(*net.TCPConn); ok {
				_ = tc.SetLinger(0)
			}
			_ = c.Close()
		}
		return
	}
	rw.WriteHeader(statusOf2(route))
	_, _ = rw.Write(cannedBody(route["body"]))
}

func statusOf2(route map[string]any) int {
	n, _ := route["status"].(json.Number)
	c, _ := n.Int64()
	if c == 0 {
		panic(fmt.Sprintf("a route with no status: %v", route))
	}
	return int(c)
}

// routesFor answers from the route the wrapping transport already picked for this request (it picked once, to record).
func (w *world) routesFor(r *http.Request) map[string]any {
	w.mu.Lock()
	defer w.mu.Unlock()
	return w.picked[r.Header.Get("X-Test-Id")]
}

// transport is the wrapper: it records the request and either injects the failure the route names or sends the request on.
type transport struct{ w *world }

type timeoutErr struct{}

func (timeoutErr) Error() string   { return "i/o timeout" }
func (timeoutErr) Timeout() bool   { return true }
func (timeoutErr) Temporary() bool { return true }

func (tr transport) RoundTrip(req *http.Request) (*http.Response, error) {
	w := tr.w
	var body any
	var raw []byte
	if req.Body != nil {
		raw, _ = io.ReadAll(req.Body)
		req.Body = io.NopCloser(bytes.NewReader(raw))
	}
	if len(raw) > 0 {
		d := json.NewDecoder(bytes.NewReader(raw))
		d.UseNumber()
		if err := d.Decode(&body); err != nil {
			w.t.Errorf("a request body that is not JSON: %v", err)
		}
	}
	hdr := map[string]string{}
	for _, k := range keepHeaders {
		if v := req.Header.Get(k); v != "" {
			hdr[k] = v
		}
	}
	if body != nil {
		hdr["content-type"] = req.Header.Get("Content-Type")
	}
	target := req.URL.RequestURI()
	w.mu.Lock()
	w.seen = append(w.seen, wsReq{Method: req.Method, Target: target, Headers: hdr, Body: body})
	w.mu.Unlock()
	route := w.pick(req.Method + " " + target)
	sent := func() {
		if t := httptrace.ContextClientTrace(req.Context()); t != nil && t.GotConn != nil {
			t.GotConn(httptrace.GotConnInfo{})
		}
	}
	switch route["fail"] {
	case "refused":
		return nil, &net.OpError{Op: "dial", Net: "tcp", Err: os.NewSyscallError("connect", syscall.ECONNREFUSED)}
	case "dns":
		return nil, &net.OpError{Op: "dial", Net: "tcp", Err: &net.DNSError{Err: "no such host", Name: "x"}}
	case "connect-timeout":
		return nil, &net.OpError{Op: "dial", Net: "tcp", Err: timeoutErr{}}
	case "timeout":
		sent()
		return nil, timeoutErr{}
	case "reset":
		sent()
		return nil, &net.OpError{Op: "read", Net: "tcp", Err: os.NewSyscallError("read", syscall.ECONNRESET)}
	case "disconnected":
		sent()
		return nil, io.EOF
	}
	// Send it on to the server, which answers from the route picked here.
	w.mu.Lock()
	w.next++
	id := strconv.Itoa(w.next)
	w.picked[id] = route
	w.mu.Unlock()
	r2 := req.Clone(req.Context())
	r2.Header.Set("X-Test-Id", id)
	u := *req.URL
	su, _ := http.NewRequest("GET", w.srv.URL, nil)
	u.Scheme, u.Host = su.URL.Scheme, su.URL.Host
	r2.URL = &u
	r2.RequestURI = ""
	if len(raw) > 0 {
		r2.Body = io.NopCloser(bytes.NewReader(raw))
	}
	resp, err := w.realTr.RoundTrip(r2)
	if err != nil {
		w.t.Logf("the test server did not answer %s: %v", req.URL, err)
	}
	return resp, err
}

func asClient(w *world, hc *http.Client) { hc.Transport = transport{w} }

