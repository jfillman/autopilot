// The triggers held equal to the Python gateway's: the topic matcher, the ledger key, the task ids, the summary an agent is given,
// the rebuilt events, and the bridge, the sweep's pure parts and the scheduler driven through the same steps (generated by
// tools/gen_gateway_registry.py into testdata/triggers.json).

func fixture(t testing.TB) map[string]json.RawMessage {
	raw, err := os.ReadFile("testdata/triggers.json")
	if err != nil {
		t.Fatal(err)
	}
	var f map[string]json.RawMessage
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	return f
}

func into(t testing.TB, raw json.RawMessage, v any) {
	t.Helper()
	if err := json.Unmarshal(raw, v); err != nil {
		t.Fatal(err)
	}
}

// norm is a value as generic JSON with nulls dropped from both sides.
func norm(t testing.TB, v any) any {
	t.Helper()
	raw, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	var out any
	_ = json.Unmarshal(raw, &out)
	return dropNil(out)
}

func dropNil(v any) any {
	switch x := v.(type) {
	case map[string]any:
		for k, e := range x {
			if e == nil {
				delete(x, k)
			} else {
				x[k] = dropNil(e)
			}
		}
	case []any:
		for i := range x {
			x[i] = dropNil(x[i])
		}
	}
	return v
}

func TestMatchingKeysAndIDsEqualPython(t *testing.T) {
	f := fixture(t)
	var am []struct {
		Pattern, Key string
		Match        bool
	}
	into(t, f["amqp"], &am)
	for _, c := range am {
		if got := triggers.AMQPTopicMatch(c.Pattern, c.Key); got != c.Match {
			t.Errorf("%q vs %q: %v, Python %v", c.Pattern, c.Key, got, c.Match)
		}
	}
	var keys []struct {
		Envelope map[string]any
		Key      *string
	}
	into(t, f["keys"], &keys)
	for _, c := range keys {
		got := triggers.TriggerKey(c.Envelope)
		want := ""
		if c.Key != nil {
			want = *c.Key
		}
		if got != want {
			t.Errorf("%v: %q, Python %q", c.Envelope, got, want)
		}
	}
	var ids []struct {
		Agent, Key, ID string
		Slot           *int64
	}
	into(t, f["task_ids"], &ids)
	for _, c := range ids {
		got := triggers.EventTaskID(c.Agent, c.Key)
		if c.Slot != nil {
			got = triggers.SlotTaskID(c.Agent, *c.Slot)
		}
		if got != c.ID {
			t.Errorf("%+v: %s", c, got)
		}
	}
	var slots []struct {
		Now, Every, Start string
		Slot              int64
	}
	into(t, f["slots"], &slots)
	for _, c := range slots {
		now, _ := dispatch.ParsePyIso(c.Now)
		every, _ := definitions.ParseInterval(c.Every)
		n, start := triggers.SlotOf(now, every)
		if n != c.Slot || dispatch.PyIso(start) != c.Start {
			t.Errorf("%+v: %d %v", c, n, start)
		}
	}
	var its []struct {
		ID   *string
		Time *string
	}
	into(t, f["id_times"], &its)
	for _, c := range its {
		id := ""
		if c.ID != nil {
			id = *c.ID
		}
		got, ok := triggers.IDTime(id)
		// Python accepts any id of 16 digits, a dash and anything; Go also requires the hash to be alphanumeric and bounded (stricter)
		if c.Time == nil {
			if ok {
				t.Errorf("%q: %v, Python none", id, got)
			}
			continue
		}
		if !ok || dispatch.PyIso(got) != *c.Time {
			t.Errorf("%q: %v %v, Python %s", id, got, ok, *c.Time)
		}
	}
	var sums []struct {
		Envelope map[string]any
		Summary  map[string]any
	}
	into(t, f["summaries"], &sums)
	for _, c := range sums {
		if got := triggers.Summarize(c.Envelope); !reflect.DeepEqual(norm(t, got), norm(t, c.Summary)) {
			t.Errorf("%v:\n go  %v\n py  %v", c.Envelope, norm(t, got), norm(t, c.Summary))
		}
	}
	var envs []struct {
		Row      map[string]any
		Envelope map[string]any
	}
	into(t, f["run_envelopes"], &envs)
	for _, c := range envs {
		got, ok := triggers.EnvelopeFromRun(c.Row)
		if c.Envelope == nil {
			if ok {
				t.Errorf("%v: an envelope from a row with no app or name", c.Row)
			}
			continue
		}
		if !ok || !reflect.DeepEqual(norm(t, got), norm(t, c.Envelope)) {
			t.Errorf("%v:\n go  %v\n py  %v", c.Row, norm(t, got), norm(t, c.Envelope))
		}
	}
	var times []struct {
		S    *string
		Time *string
	}
	into(t, f["times"], &times)
	for _, c := range times {
		s := ""
		if c.S != nil {
			s = *c.S
		}
		got, ok := triggers.ParseRunTime(s)
		if c.Time == nil {
			if ok {
				t.Errorf("%q parsed: %v", s, got)
			}
		} else if want, _ := dispatch.ParsePyIso(*c.Time); !ok || !got.Equal(want) { // the same instant (Go keeps UTC, Python the offset it was given)
			t.Errorf("%q: %v %v, Python %s", s, got, ok, *c.Time)
		}
	}
}

