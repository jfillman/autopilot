type pyDone struct {
	Agent   string
	Result  string
	Via     string
	New     bool
	Replay  bool
	Session string
	Run     string
	Rule    string
}

func ledgerRows(l *triggers.MemoryLedger) []map[string]any {
	var out []map[string]any
	for _, r := range l.Rows() {
		m := map[string]any{"agent": r.Agent, "key": r.Key, "via": r.Via, "state": r.State, "claimed_at": dispatch.PyIso(r.ClaimedAt)}
		if r.EventID != nil {
			m["event_id"] = *r.EventID
		}
		if r.Session != nil {
			m["session"] = *r.Session
		}
		if r.Run != nil {
			m["run"] = *r.Run
		}
		out = append(out, m)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i]["agent"] != out[j]["agent"] {
			return out[i]["agent"].(string) < out[j]["agent"].(string)
		}
		return out[i]["key"].(string) < out[j]["key"].(string)
	})
	return out
}

func TestTheBridgeEqualsPython(t *testing.T) {
	f := fixture(t)
	var want struct {
		Steps []struct {
			Envelope map[string]any
			Via      string
			At       int
			Done     []pyDone
		}
		Rows     []map[string]any
		Opens    [][]string
		Launches []string
		Events   []map[string]any
		Counters struct {
			Outcomes map[string]float64
			Missed   map[string]float64
		}
	}
	into(t, f["bridge"], &want)
	gw := newGW()
	for n, d := range agentDefs(t) {
		gw.defs[n] = d
	}
	// the Python fake keeps a hold rule per agent ("" is none); hold rules change between steps
	ledger := &triggers.MemoryLedger{}
	m := &triggers.Recorder{}
	now := time.Date(2026, 9, 26, 12, 0, 0, 0, time.UTC)
	b, err := triggers.NewBridge(gw, ledger, triggers.BridgeConfig{BaseURL: "http://glidepath.invalid", TokenFile: "/dev/null", Now: func() time.Time { return now }}, m, nil)
	if err != nil {
		t.Fatal(err)
	}
	rules := map[int]string{7: "R024", 8: "R001"} // the step at which any-agent's rule changes (as the generator does), back to none at 9
	for i, st := range want.Steps {
		now = time.Date(2026, 9, 26, 12, 0, 0, 0, time.UTC).Add(time.Duration(st.At) * time.Second)
		if r, ok := rules[i]; ok {
			gw.holdRule["any-agent"] = r
		} else if i == 9 {
			delete(gw.holdRule, "any-agent")
		}
		got, err := b.Handle(context.Background(), st.Envelope, st.Via)
		if err != nil {
			t.Fatal(err)
		}
		var gd []pyDone
		for _, o := range got {
			gd = append(gd, pyDone{o.Agent, o.Result, o.Via, o.New, o.Replay, o.Session, o.Run, o.Rule})
		}
		wd := append([]pyDone(nil), st.Done...)
		for k := range wd {
			if wd[k].Rule == "" {
				wd[k].Rule = ""
			}
		}
		if !reflect.DeepEqual(gd, wd) && !(len(gd) == 0 && len(wd) == 0) {
			t.Errorf("step %d (%v):\n go  %+v\n py  %+v", i, st.Envelope["id"], gd, wd)
		}
	}
	if got := ledgerRows(ledger); !reflect.DeepEqual(norm(t, got), norm(t, want.Rows)) {
		t.Errorf("ledger rows:\n go  %v\n py  %v", norm(t, got), norm(t, want.Rows))
	}
	var opens [][]string
	for _, o := range gw.opens {
		parts := strings.SplitN(o, "/", 2)
		opens = append(opens, parts)
	}
	if len(opens) != len(want.Opens) {
		t.Errorf("%d opens, Python %d", len(opens), len(want.Opens))
	}
	for i, o := range want.Opens {
		if i < len(opens) && (opens[i][0] != o[0] || opens[i][1] != o[2]) {
			t.Errorf("open %d: %v, Python %v", i, opens[i], o)
		}
	}
	if !reflect.DeepEqual(gw.launches, want.Launches) {
		t.Errorf("launches %v, Python %v", gw.launches, want.Launches)
	}
	var events []map[string]any
	for i := range gw.events {
		rec, err := dispatch.EventFromSummary(gw.events[i], gw.outcomes[i], time.Date(2026, 9, 26, 12, 0, 0, 0, time.UTC), "glidepath")
		if err != nil {
			t.Fatal(err)
		}
		events = append(events, rec.View())
	}
	if !reflect.DeepEqual(norm(t, events), norm(t, want.Events)) {
		t.Errorf("history:\n go  %v\n py  %v", norm(t, events), norm(t, want.Events))
	}
	for k, v := range want.Counters.Outcomes {
		if float64(m.Count("outcome/"+k)) != v {
			t.Errorf("outcome counter %s: %d, Python %v", k, m.Count("outcome/"+k), v)
		}
	}
	for k, v := range want.Counters.Missed {
		if float64(m.Count("missed/"+k)) != v {
			t.Errorf("missed counter %s: %d, Python %v", k, m.Count("missed/"+k), v)
		}
	}
}

func TestWatchedAppsEqualPython(t *testing.T) {
	f := fixture(t)
	var want []struct {
		Set   string
		Found bool
		Apps  []string
	}
	into(t, f["watched"], &want)
	d := agentDefs(t)
	sets := map[string]map[string]*definitions.Definition{"triage": {"t": d["triage-agent"]}, "strict": {"s": d["strict-agent"]}, "wild": {"w": d["any-agent"]},
		"none": {"n": d["nightly-reviewer"]}}
	for _, w := range want {
		found, apps := triggers.WatchedApps(sets[w.Set])
		var got []string
		for a := range apps {
			got = append(got, a)
		}
		sort.Strings(got)
		if found != w.Found || !reflect.DeepEqual(append([]string{}, got...), append([]string{}, w.Apps...)) {
			t.Errorf("%s: %v %v, Python %v %v", w.Set, found, got, w.Found, w.Apps)
		}
	}
}

func TestTheSchedulerEqualsPython(t *testing.T) {
	f := fixture(t)
	var want struct {
		Ticks []struct {
			Label string
			At    string
			Done  []struct {
				Agent   string
				Slot    int64
				Result  string
				Session string
				Run     string
			}
		}
		Rows     []map[string]any
		Opens    [][]string
		Counters struct {
			Launches map[string]float64
			Missed   map[string]float64
		}
	}
	into(t, f["scheduler"], &want)
	gw := newGW()
	gw.defs["nightly-reviewer"] = agentDefs(t)["nightly-reviewer"]
	ledger := &triggers.MemoryLedger{}
	m := &triggers.Recorder{}
	now := time.Date(2026, 11, 14, 0, 2, 0, 0, time.UTC)
	_, _ = ledger.Cursor(context.Background(), "schedule:nightly-reviewer", time.Date(2026, 11, 10, 6, 0, 0, 0, time.UTC))
	s := triggers.NewScheduler(gw, ledger, func() time.Time { return now }, m, nil)
	for _, tk := range want.Ticks {
		now, _ = dispatch.ParsePyIso(tk.At)
		got := s.Tick(context.Background())
		type d struct {
			Agent   string
			Slot    int64
			Result  string
			Session string
			Run     string
		}
		var gd, wd []d
		for _, g := range got {
			gd = append(gd, d{g.Agent, g.Slot, g.Result, g.Session, g.Run})
		}
		for _, w := range tk.Done {
			wd = append(wd, d{w.Agent, w.Slot, w.Result, w.Session, w.Run})
		}
		if !reflect.DeepEqual(gd, wd) && !(len(gd) == 0 && len(wd) == 0) {
			t.Errorf("tick %s:\n go  %+v\n py  %+v", tk.Label, gd, wd)
		}
	}
	if got := ledgerRows(ledger); !reflect.DeepEqual(norm(t, got), norm(t, want.Rows)) {
		t.Errorf("ledger rows:\n go  %v\n py  %v", norm(t, got), norm(t, want.Rows))
	}
	if len(gw.opens) != len(want.Opens) {
		t.Errorf("%d opens, Python %d", len(gw.opens), len(want.Opens))
	}
	for k, v := range want.Counters.Launches {
		if float64(m.Count("slot_launch/"+k)) != v {
			t.Errorf("launch counter %s: %d, Python %v", k, m.Count("slot_launch/"+k), v)
		}
	}
	for k, v := range want.Counters.Missed {
		if float64(m.Count("slot_missed/"+k)) != v {
			t.Errorf("missed counter %s: %d, Python %v", k, m.Count("slot_missed/"+k), v)
		}
	}
}
